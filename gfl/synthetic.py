"""Generate SYNTHETIC capture logs so the pipeline runs without a GPU.

Run:  python -m gfl.synthetic   (writes data/sample/synthetic_lyra_scalability/)

Everything this module writes is labeled synthetic: file names start with
SYNTHETIC_, the manifest marks data_kind=synthetic, the process name in the logs
is the real one but the notes column says the data is generated, and every
summary and chart produced from it carries a SYNTHETIC banner.

The numbers below are INVENTED. They are shaped to look like a real capture
(CPU/GPU-bound behavior, noise, hitches, a warmup period, run-to-run spread)
so that parsing, trimming, metrics, and plots are exercised realistically.
They are not estimates of any real GPU or of Lyra performance, and nothing in the
study's findings may be derived from them.
"""

from __future__ import annotations

import gzip
import zlib
from datetime import datetime, timedelta
from pathlib import Path

import numpy as np
import pandas as pd

from gfl.config import PRESET_LEVELS, RunConfig, load_experiment
from gfl.manifest import write_manifest

DEFAULT_CONFIG = Path("configs/lyra_scalability.yaml")
DEFAULT_OUT = Path("data/sample/synthetic_lyra_scalability")
NOTE = "SYNTHETIC: generated by gfl.synthetic, not a measurement"

# Invented cost model (ms). GPU cost grows with pixel count, with a share of the
# frame that does not scale with resolution; CPU cost depends on preset only.
_GPU_MS_AT_1080P = {"low": 2.6, "medium": 4.0, "high": 6.3, "epic": 9.8}
_CPU_MS = {"low": 4.1, "medium": 4.5, "high": 5.0, "epic": 5.6}
_RESOLUTION_INDEPENDENT_SHARE = 0.3
_PRESENT_OVERHEAD_MS = 0.15


def _seed(*parts: object) -> int:
    return zlib.crc32("|".join(map(str, parts)).encode())


def simulate_frames(run: RunConfig, run_index: int, duration_s: float, warmup_s: float) -> pd.DataFrame:
    """Simulate one run's per-frame CPU busy, GPU busy, and frame times."""
    rng = np.random.default_rng(_seed(run.config_id, run_index))
    scale = run.resolution.pixels / (1920 * 1080)
    gpu_base = _GPU_MS_AT_1080P[run.preset] * (
        _RESOLUTION_INDEPENDENT_SHARE + (1 - _RESOLUTION_INDEPENDENT_SHARE) * scale
    )
    cpu_base = _CPU_MS[run.preset]
    run_factor = rng.normal(1.0, 0.008)  # run-to-run spread
    level = PRESET_LEVELS[run.preset]
    hitch_rate = 0.04 + 0.03 * level  # hitches per second after warmup

    rows = []
    t = rng.uniform(0.2, 0.5)  # first present lands a little after capture starts
    drift = 0.0
    while t < duration_s + 1.0:
        # Slow scene-dependent load: the camera path passes heavier areas on a
        # ~20 s cycle (same phase every run, like a fixed flythrough), plus a
        # small random walk.
        drift = 0.97 * drift + rng.normal(0, 0.004)
        scene_load = 1.0 + 0.06 * np.sin(2 * np.pi * t / 20.0) + drift
        cpu = cpu_base * run_factor * scene_load * rng.lognormal(0, 0.05)
        gpu = gpu_base * run_factor * scene_load * rng.lognormal(0, 0.04)
        frame = max(cpu, gpu) + _PRESENT_OVERHEAD_MS

        # Hitches (shader compilation, streaming). Much more frequent while
        # warming up, which is exactly why the first 10 s are dropped.
        rate = 2.5 if t < warmup_s else hitch_rate
        if rng.random() < rate * frame / 1000.0:
            frame += frame * rng.uniform(1.5, 3.5)

        rows.append((t, frame, cpu, gpu))
        t += frame / 1000.0

    return pd.DataFrame(rows, columns=["t", "frametime", "cpu_busy", "gpu_busy"])


def to_presentmon(sim: pd.DataFrame, process: str) -> pd.DataFrame:
    """PresentMon 2.x column layout (subset of the default columns)."""
    ft = sim["frametime"]
    return pd.DataFrame(
        {
            "Application": process,
            "ProcessID": 14872,
            "SwapChainAddress": "0x000001D3A2F4B6C0",
            "PresentRuntime": "DXGI",
            "SyncInterval": 0,
            "PresentFlags": 512,
            "AllowsTearing": 1,
            "PresentMode": "Hardware: Independent Flip",
            "CPUStartTime": sim["t"].round(6),
            "MsCPUBusy": sim["cpu_busy"].round(4),
            "MsCPUWait": (ft - sim["cpu_busy"]).clip(lower=0).round(4),
            "MsGPULatency": (sim["cpu_busy"] * 0.4).round(4),
            "MsGPUTime": (sim["gpu_busy"] * 1.02).round(4),
            "MsGPUBusy": sim["gpu_busy"].round(4),
            "MsGPUWait": (ft - sim["gpu_busy"]).clip(lower=0).round(4),
            "MsBetweenPresents": ft.round(4),
            "MsInPresentAPI": 0.12,
            "MsUntilDisplayed": (sim["gpu_busy"] * 0.6 + 1.1).round(4),
        }
    )


def to_frameview(sim: pd.DataFrame, process: str, rng: np.random.Generator) -> pd.DataFrame:
    """Approximation of FrameView's per-frame log (PresentMon 1.x style + telemetry).

    FrameView watches the same Present() events as PresentMon, but it is started
    by hand with a hotkey, so it starts a little later and stops a little earlier,
    and it rounds differently. The column layout is an assumption until checked
    against a real export (Phase 2).
    """
    start = rng.uniform(0.6, 1.2)
    stop = sim["t"].iloc[-1] - rng.uniform(0.5, 1.0)
    part = sim[(sim["t"] >= start) & (sim["t"] <= stop)]
    ft = part["frametime"] + rng.normal(0, 0.002, len(part))  # timer resolution differences
    util = np.clip(100 * part["gpu_busy"] / part["frametime"] + rng.normal(0, 1.5, len(part)), 0, 99)
    return pd.DataFrame(
        {
            "Application": process,
            "ProcessID": 14872,
            "SwapChainAddress": "0x000001D3A2F4B6C0",
            "Runtime": "DXGI",
            "SyncInterval": 0,
            "PresentFlags": 512,
            "AllowsTearing": 1,
            "PresentMode": "Hardware: Independent Flip",
            "Dropped": 0,
            "TimeInSeconds": (part["t"] - start + 12.5).round(5),  # FrameView's own clock
            "MsBetweenPresents": ft.round(3),
            "MsInPresentAPI": 0.12,
            "MsUntilRenderComplete": (part["gpu_busy"] * 0.6).round(3),
            "MsUntilDisplayed": (part["gpu_busy"] * 0.6 + 1.1).round(3),
            "GPU0Util(%)": util.round(0).astype(int),
        }
    )


def to_nvidia_smi(run: RunConfig, run_index: int, duration_s: float, warmup_s: float,
                  start: datetime) -> str:
    """nvidia-smi --query-gpu=timestamp,memory.used,utilization.gpu --format=csv,nounits."""
    rng = np.random.default_rng(_seed("vram", run.config_id, run_index))
    scale = run.resolution.pixels / (1920 * 1080)
    level = PRESET_LEVELS[run.preset]
    steady = 2600 + [0, 600, 1500, 2600][level] + 700 * (scale - 1)
    lines = ["timestamp, memory.used [MiB], utilization.gpu [%]"]
    for i in range(int(duration_s / 0.5) + 1):
        t = i * 0.5
        ramp = 0.7 + 0.3 * min(1.0, t / warmup_s)  # streaming fills VRAM early on
        mem = steady * ramp + rng.normal(0, 40)
        util = min(99, 60 + 10 * level + 5 * scale + rng.normal(0, 3))
        stamp = (start + timedelta(seconds=t)).strftime("%Y/%m/%d %H:%M:%S.%f")[:-3]
        lines.append(f"{stamp}, {mem:.0f}, {util:.0f}")
    return "\n".join(lines) + "\n"


def generate(config_path: Path = DEFAULT_CONFIG, out_dir: Path = DEFAULT_OUT) -> Path:
    experiment = load_experiment(config_path)
    cap = experiment.capture
    out_dir.mkdir(parents=True, exist_ok=True)
    clock = datetime(2026, 1, 1, 12, 0, 0)  # arbitrary fixed start so output is reproducible

    manifest_rows = []
    for run in experiment.expand():
        for run_index in range(1, cap.runs + 1):
            run_id = f"{run.config_id}_run{run_index}"
            sim = simulate_frames(run, run_index, cap.duration_s, cap.warmup_s)
            rng = np.random.default_rng(_seed("frameview", run_id))

            pm_name = f"SYNTHETIC_presentmon_{run_id}.csv.gz"
            fv_name = f"SYNTHETIC_frameview_{run_id}.csv.gz"
            smi_name = f"SYNTHETIC_nvidia-smi_{run_id}.csv"
            _write_gz(to_presentmon(sim, experiment.scene.process_name), out_dir / pm_name)
            _write_gz(to_frameview(sim, experiment.scene.process_name, rng), out_dir / fv_name)
            (out_dir / smi_name).write_text(
                to_nvidia_smi(run, run_index, cap.duration_s, cap.warmup_s, clock), encoding="utf-8"
            )

            manifest_rows.append(
                {
                    "run_id": run_id,
                    "experiment": run.experiment,
                    "config_id": run.config_id,
                    "scene": run.scene,
                    "preset": run.preset,
                    "resolution": str(run.resolution),
                    "dlss_mode": run.dlss_mode,
                    "frame_generation": run.frame_generation,
                    "inference_streams": run.inference_streams,
                    "tag": run.tag,
                    "run_index": run_index,
                    "duration_s": cap.duration_s,
                    "warmup_s": cap.warmup_s,
                    "data_kind": "synthetic",
                    "presentmon_csv": pm_name,
                    "frameview_csv": fv_name,
                    "telemetry_csv": smi_name,
                    "captured_at": clock.isoformat(),
                    "notes": NOTE,
                }
            )
            clock += timedelta(seconds=cap.duration_s + cap.cooldown_s)

    return write_manifest(manifest_rows, out_dir)


def _write_gz(df: pd.DataFrame, path: Path) -> None:
    # mtime=0 keeps the gzip bytes identical between regenerations (clean diffs).
    with open(path, "wb") as raw, gzip.GzipFile(fileobj=raw, mode="wb", mtime=0) as gz:
        gz.write(df.to_csv(index=False).encode("utf-8"))


if __name__ == "__main__":
    manifest = generate()
    print(f"Wrote SYNTHETIC sample data. Manifest: {manifest}")
