"""`gfl analyze`: manifest -> per-run metrics -> per-config summary -> table + charts."""

from __future__ import annotations

from dataclasses import dataclass, field
from pathlib import Path

import pandas as pd

from gfl import manifest as mf
from gfl import plots
from gfl.config import PRESET_LEVELS, Resolution
from gfl.metrics import compute_run_metrics, summarize_runs, trim_window
from gfl.parse import load_gpu_telemetry_csv, load_presentmon_csv
from gfl.tables import markdown_table

CONFIG_KEYS = [
    "config_id", "scene", "preset", "resolution", "dlss_mode",
    "frame_generation", "inference_streams", "tag",
]

SYNTHETIC_BANNER = (
    "SYNTHETIC DATA: generated by gfl.synthetic to exercise the pipeline. "
    "These numbers are not measurements and must not be cited as results."
)


@dataclass
class AnalysisResult:
    data_kind: str
    per_run: pd.DataFrame
    summary: pd.DataFrame
    out_dir: Path
    outputs: list[Path] = field(default_factory=list)

    @property
    def is_synthetic(self) -> bool:
        return self.data_kind == "synthetic"


def load_run_frames(run_dir: Path, row: pd.Series) -> tuple[pd.DataFrame, pd.DataFrame | None]:
    """Parse and trim one run's PresentMon log and (optional) telemetry log."""
    frames = load_presentmon_csv(mf.resolve(run_dir, row["presentmon_csv"]))
    frames = trim_window(frames, row["warmup_s"], row["duration_s"])

    telemetry = None
    tel_path = mf.resolve(run_dir, row["telemetry_csv"])
    if tel_path is not None:
        telemetry = trim_window(load_gpu_telemetry_csv(tel_path), row["warmup_s"], row["duration_s"])
    return frames, telemetry


def analyze(run_dir: str | Path, out_dir: str | Path | None = None,
            trace_resolution: str | None = None) -> AnalysisResult:
    run_dir = Path(run_dir)
    manifest = mf.read_manifest(run_dir)
    data_kind = mf.data_kind_of(manifest)
    synthetic = data_kind == "synthetic"

    if out_dir is None:
        experiment = "+".join(sorted(manifest["experiment"].unique()))
        out_dir = Path("results") / ("synthetic" if synthetic else "") / experiment
    out_dir = Path(out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    prefix = "SYNTHETIC_" if synthetic else ""

    # 1. Per-run metrics. Keep run 1's trimmed frames for the trace chart.
    per_run_rows, traces = [], {}
    for _, row in manifest.iterrows():
        frames, telemetry = load_run_frames(run_dir, row)
        metrics = compute_run_metrics(frames, telemetry)
        per_run_rows.append({**row[CONFIG_KEYS + ["run_id", "run_index"]].to_dict(),
                             **metrics.as_dict()})
        if row["run_index"] == 1:
            traces[row["config_id"]] = frames
    per_run = _sort_configs(pd.DataFrame(per_run_rows))
    per_run["data_kind"] = data_kind

    # 2. One summary row per config (mean across runs + run-to-run spread).
    summary_rows = []
    for _, group in per_run.groupby("config_id", sort=False):
        summary_rows.append({**group.iloc[0][CONFIG_KEYS].to_dict(), **summarize_runs(group)})
    summary = _sort_configs(pd.DataFrame(summary_rows))
    summary["data_kind"] = data_kind

    result = AnalysisResult(data_kind, per_run, summary, out_dir)

    # 3. Write tables.
    per_run_path = out_dir / f"{prefix}per_run_metrics.csv"
    summary_path = out_dir / f"{prefix}summary.csv"
    per_run.to_csv(per_run_path, index=False, float_format="%.3f")
    summary.to_csv(summary_path, index=False, float_format="%.3f")
    md_path = out_dir / f"{prefix}summary.md"
    md_path.write_text(summary_markdown(summary, synthetic), encoding="utf-8")
    result.outputs += [summary_path, per_run_path, md_path]

    # 4. Charts.
    banner = SYNTHETIC_BANNER if synthetic else None
    resolution = trace_resolution or _default_trace_resolution(summary)
    trace_configs = summary[summary["resolution"] == resolution]
    if trace_configs.empty:
        raise ValueError(f"no configs at resolution {resolution}; "
                         f"available: {sorted(summary['resolution'].unique())}")
    result.outputs.append(plots.frametime_trace(
        {r.preset: traces[r.config_id] for r in trace_configs.itertuples()},
        title=f"Frame time over the measured window, {resolution} (run 1 of each preset)",
        path=out_dir / f"{prefix}frametime_trace_{resolution}.png",
        banner=banner,
    ))
    result.outputs.append(plots.fps_by_config(
        summary,
        path=out_dir / f"{prefix}fps_by_preset_and_resolution.png",
        banner=banner,
    ))
    return result


DISPLAY_COLUMNS = {
    "preset": "Preset",
    "resolution": "Resolution",
    "avg_fps": "Avg FPS",
    "avg_fps_cv_pct": "Run CV %",
    "low_1pct_fps": "1% low",
    "low_01pct_fps": "0.1% low",
    "p99_frametime_ms": "p99 ms",
    "stutters_per_min": "Stutters/min",
    "gpu_busy_pct": "GPU busy %",
    "vram_peak_mib": "VRAM peak MiB",
}


def summary_display_table(summary: pd.DataFrame) -> pd.DataFrame:
    table = summary[list(DISPLAY_COLUMNS)].rename(columns=DISPLAY_COLUMNS).copy()
    for col, digits in [("Avg FPS", 1), ("Run CV %", 2), ("1% low", 1), ("0.1% low", 1),
                        ("p99 ms", 2), ("Stutters/min", 1), ("GPU busy %", 1),
                        ("VRAM peak MiB", 0)]:
        table[col] = table[col].map(lambda v, d=digits: "n/a" if pd.isna(v) else f"{v:.{d}f}")
    flagged = summary["low_01pct_low_confidence"].to_numpy()
    table.loc[flagged, "0.1% low"] = table.loc[flagged, "0.1% low"] + "*"
    return table


def summary_markdown(summary: pd.DataFrame, synthetic: bool) -> str:
    lines = []
    if synthetic:
        lines += [f"> **{SYNTHETIC_BANNER}**", ""]
    lines += ["# Benchmark summary", "",
              "Mean of per-run metrics after dropping the warmup window. "
              "Run CV % is the run-to-run coefficient of variation of average FPS.", "",
              markdown_table(summary_display_table(summary)), ""]
    if summary["low_01pct_low_confidence"].any():
        lines.append("\\* 0.1% low rests on fewer than 5 frames per run; treat it as indicative.")
    return "\n".join(lines) + "\n"


def _sort_configs(df: pd.DataFrame) -> pd.DataFrame:
    order = df["preset"].map(lambda p: PRESET_LEVELS.get(p, 99))
    pixels = df["resolution"].map(lambda r: Resolution.parse(r).pixels)
    return (df.assign(_o=order, _p=pixels)
              .sort_values(["_o", "_p", "dlss_mode", "frame_generation", "inference_streams", "tag"]
                           + (["run_index"] if "run_index" in df.columns else []))
              .drop(columns=["_o", "_p"]).reset_index(drop=True))


def _default_trace_resolution(summary: pd.DataFrame) -> str:
    # 1440p if present (the middle of the matrix), otherwise the first resolution.
    resolutions = list(dict.fromkeys(summary["resolution"]))
    return "2560x1440" if "2560x1440" in resolutions else resolutions[0]
